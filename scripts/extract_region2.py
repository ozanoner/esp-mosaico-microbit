#!/usr/bin/env python3
"""Extract region 2 from a mkc-built hex into the firmware's flash fixture.

    python3 scripts/extract_region2.py build/dice.hex
    python3 scripts/extract_region2.py build/dice.hex --check

The device never parses a 1.3 MB hex: it only streams region 2, because the
SoftDevice and DAL are already on the micro:bit. So the payload that mb_flash
streams is committed as a fixture — `components/mb_flash/mb_fixture.bin`
plus a generated header with the geometry and hashes — and this script is how it
is (re)produced.

`--check` regenerates in memory and compares against the committed files, so a
toolchain drift that changes the image is a hard failure rather than a quiet
change to what gets flashed.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "tools" / "hexkit"))

import hexkit  # noqa: E402  (path set above)

FIXTURE_DIR = REPO / "firmware" / "projects" / "microbit_studio" / "components" / "mb_flash"
BIN_PATH = FIXTURE_DIR / "mb_fixture.bin"
HEADER_PATH = FIXTURE_DIR / "include" / "mb_fixture.h"


def build(hex_path: Path) -> tuple[bytes, bytes, str]:
    """Return (region bytes, header text, region sha256 hex)."""
    image = hexkit.load_hex(hex_path)
    magic = image.dal_magic_address()
    template_hash, program_hash = image.hashes()
    start, end = image.region2()
    blocks = image.blocks()
    region = b"".join(data for _, data in blocks)
    if len(region) != end - start:
        raise SystemExit(f"block packing covers {len(region)} B, region is {end - start} B")

    header = f"""// Generated by scripts/extract_region2.py — do not edit.
//
// Source hex: {hex_path.name}
// Region 2 is streamed by mb_flash; the SoftDevice and DAL are already on the
// device, so the firmware only carries the part that changes.
//
// Geometry and hashes come from tools/hexkit (the reference implementation);
// mb_payload's host test proves the C port agrees with it byte for byte.

#pragma once

#include <stdint.h>

#define MB_FIXTURE_MAGIC_ADDRESS 0x{magic:05X}u
#define MB_FIXTURE_REGION2_START 0x{start:05X}u
#define MB_FIXTURE_REGION2_END 0x{end:05X}u /* exclusive */
#define MB_FIXTURE_BLOCK_COUNT {len(blocks)}u
#define MB_FIXTURE_TEMPLATE_HASH_INIT \\
    {{ {", ".join(f"0x{byte:02X}" for byte in template_hash)} }}
#define MB_FIXTURE_PROGRAM_HASH_INIT \\
    {{ {", ".join(f"0x{byte:02X}" for byte in program_hash)} }}
#define MB_FIXTURE_REGION_SHA256 "{hashlib.sha256(region).hexdigest()}"
"""
    return region, header.encode(), hashlib.sha256(region).hexdigest()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("hex", type=Path, help="mkc-built .hex to extract region 2 from")
    parser.add_argument("--check", action="store_true",
                        help="compare against the committed fixture instead of writing")
    args = parser.parse_args(argv)

    region, header, sha = build(args.hex)
    bin_path = BIN_PATH
    header_path = HEADER_PATH

    if args.check:
        problems = []
        if not bin_path.is_file():
            problems.append(f"missing {bin_path.relative_to(REPO)}")
        elif bin_path.read_bytes() != region:
            problems.append(f"{BIN_PATH.name} differs from {args.hex.name}")
        if not header_path.is_file():
            problems.append(f"missing {header_path.relative_to(REPO)}")
        elif header_path.read_bytes() != header:
            problems.append(f"{HEADER_PATH.name} differs from {args.hex.name}")
        for problem in problems:
            print(f"extract_region2: {problem}")
        if problems:
            return 1
        print(f"fixture matches {args.hex.name}: {len(region)} B of region 2, sha256 {sha[:16]}…")
        return 0

    FIXTURE_DIR.mkdir(parents=True, exist_ok=True)
    bin_path.write_bytes(region)
    header_path.write_bytes(header)
    print(f"wrote {bin_path.relative_to(REPO)} ({len(region)} B)")
    print(f"wrote {header_path.relative_to(REPO)}")
    print(f"region sha256 {sha}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
